def detect_dangers(detections):
    found = []
    for d in detections:
        cls = d.get("class")
        if cls in DANGEROUS_OBJECTS:
            found.append(DANGEROUS_OBJECTS[cls])
    return found
def build_suggestions(mode):
    result = []
    if mode in USE_CASES:
        result.extend(USE_CASES[mode])
    if mode not in ["capabilities", "general_chat", "greeting", "help"]:
        result.extend(USE_CASES["safety"])
        result.extend(USE_CASES["general"][:2])
    else:
        result.extend(USE_CASES["general_chat"])
    return list(dict.fromkeys(result))[:12]
def build_response(
    ai_reply,
    detections=None,
    mode="general",
    extracted_text=None,
    image_b64=None,
    audio_b64=None,
):
    detections = detections or []
    dangers = detect_dangers(detections)
    response = {
        "status":        "success",
        "message":       ai_reply,
        "detections":    detections,
        "suggestions":   build_suggestions(mode),
        "danger_alerts": dangers,
        "extra":         {},
    }
    if extracted_text:
        response["extra"]["text"] = extracted_text
    if image_b64:
        response["image_b64"] = image_b64
    if audio_b64:
        response["audio_b64"] = audio_b64
    return response